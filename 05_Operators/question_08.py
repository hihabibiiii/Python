# Question 8 (Medium):
# Use the ** (exponentiation) operator to:
#   1. Compute 2 to the power of 10.
#   2. Compute 3 to the power of 5.
#   3. Compute the square root of 144 using ** 0.5.

# Solution:
print("2 ** 10      =", 2 ** 10)
print("3 ** 5       =", 3 ** 5)
print("144 ** 0.5   =", 144 ** 0.5, "(square root of 144)")
print("27 ** (1/3)  =", 27 ** (1/3), "(cube root of 27)")

# Output:
# 2 ** 10      = 1024
# 3 ** 5       = 243
# 144 ** 0.5   = 12.0 (square root of 144)
# 27 ** (1/3)  = 3.0  (cube root of 27)
