# Question 1 (Easy):
# Use all arithmetic operators on two numbers: a = 15, b = 4.
# Print each result with a descriptive label.

# Solution:
a = 15
b = 4

print("a =", a, ", b =", b)
print("a + b  =", a + b)    # Addition
print("a - b  =", a - b)    # Subtraction
print("a * b  =", a * b)    # Multiplication
print("a / b  =", a / b)    # Division (float)
print("a // b =", a // b)   # Floor division
print("a % b  =", a % b)    # Modulo (remainder)
print("a ** b =", a ** b)   # Exponentiation

# Output:
# a = 15 , b = 4
# a + b  = 19
# a - b  = 11
# a * b  = 60
# a / b  = 3.75
# a // b = 3
# a % b  = 3
# a ** b = 50625
