# Question 2 (Easy):
# Use all comparison operators on two numbers: x = 10, y = 20.
# Print True or False for each comparison with a label.

# Solution:
x = 10
y = 20

print("x =", x, ", y =", y)
print("x == y :", x == y)   # Equal
print("x != y :", x != y)   # Not equal
print("x < y  :", x < y)    # Less than
print("x > y  :", x > y)    # Greater than
print("x <= y :", x <= y)   # Less than or equal
print("x >= y :", x >= y)   # Greater than or equal

# Output:
# x = 10 , y = 20
# x == y : False
# x != y : True
# x < y  : True
# x > y  : False
# x <= y : True
# x >= y : False
