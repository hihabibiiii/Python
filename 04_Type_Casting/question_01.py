# Question 1 (Easy):
# Convert the string '42' to an integer using int().
# Print its value and type before and after conversion.

# Solution:
string_value = '42'
print("Before:", string_value, "| Type:", type(string_value))

integer_value = int(string_value)
print("After :", integer_value, "| Type:", type(integer_value))

# Output:
# Before: 42 | Type: <class 'str'>
# After : 42 | Type: <class 'int'>
