# Question 7 (Medium):
# Convert bool to int: True → 1, False → 0.
# Demonstrate by multiplying these integer representations with a number.

# Solution:
print("True as int :", int(True))
print("False as int:", int(False))

multiplier = 7
print(f"\nTrue  * {multiplier} =", int(True) * multiplier)
print(f"False * {multiplier} =", int(False) * multiplier)

# Output:
# True as int : 1
# False as int: 0
#
# True  * 7 = 7
# False * 7 = 0
