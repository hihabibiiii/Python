# Question:
# Take a number from the user and print 'Positive' if it is greater than 0,
# or 'Negative' if it is less than 0.
#
# Example:
#   Input: 5   -> Output: Positive
#   Input: -3  -> Output: Negative

number = float(input("Enter a number: "))

if number > 0:
    print("Positive")
else:
    print("Negative")
