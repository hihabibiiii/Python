# Question 6 (Medium):
# Take the user's name and age as input.
# Print a sentence using an f-string that includes both values.

# Solution:
name = input("Enter your name: ")
age = int(input("Enter your age: "))

print(f"Hi, {name}! You are {age} years old.")

# Example Input / Output:
# Enter your name: Maria
# Enter your age: 22
# Hi, Maria! You are 22 years old.
