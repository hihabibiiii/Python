# Question 4 (Easy):
# Use the `sep` parameter of print() to print multiple values
# separated by ' | ' instead of a space.

# Solution:
print("Python", "Java", "C++", "JavaScript", sep=" | ")
print(2020, 2021, 2022, 2023, sep=" | ")

# Output:
# Python | Java | C++ | JavaScript
# 2020 | 2021 | 2022 | 2023
