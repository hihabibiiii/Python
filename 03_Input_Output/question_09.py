# Question 9 (Medium):
# Take 3 student names from the user using input().
# Print them as a numbered list.

# Solution:
name1 = input("Enter name of student 1: ")
name2 = input("Enter name of student 2: ")
name3 = input("Enter name of student 3: ")

print("\nStudent List:")
print("1.", name1)
print("2.", name2)
print("3.", name3)

