# Question:
# Take first name and last name from the user.
# Concatenate them with a space in between and print the full name.

# Example:
# First name: John
# Last name: Doe
# Full name: John Doe

first = input("First name: ")
last = input("Last name: ")

full_name = first + " " + last
print(f"Full name: {full_name}")
