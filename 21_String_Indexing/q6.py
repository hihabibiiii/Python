# Question: Print characters at indices 0, 2, and 4 of a string.
# Access specific positions using indexing.
# Example:
#   Input: "Python"
#   Output: P t o

text = input("Enter a string (at least 5 characters): ")
print("Character at index 0:", text[0])
print("Character at index 2:", text[2])
print("Character at index 4:", text[4])
