# Question 4 (Easy):
# Create one example each of: list, tuple, set, and dictionary,
# each containing 3 elements.
# Print each collection and its type.

# Solution:
my_list = [1, 2, 3]
my_tuple = (4, 5, 6)
my_set = {7, 8, 9}
my_dict = {"a": 1, "b": 2, "c": 3}

print(my_list, "->", type(my_list))
print(my_tuple, "->", type(my_tuple))
print(my_set, "->", type(my_set))
print(my_dict, "->", type(my_dict))

# Output:
# [1, 2, 3] -> <class 'list'>
# (4, 5, 6) -> <class 'tuple'>
# {7, 8, 9} -> <class 'set'>
# {'a': 1, 'b': 2, 'c': 3} -> <class 'dict'>
