# Question 1 (Easy):
# Print the data type of each of the following values:
#   42, 3.14, 'hello', True
# Use the type() function for each.

# Solution:
print(type(42))
print(type(3.14))
print(type('hello'))
print(type(True))

# Output:
# <class 'int'>
# <class 'float'>
# <class 'str'>
# <class 'bool'>
