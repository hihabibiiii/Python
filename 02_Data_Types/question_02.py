# Question 2 (Easy):
# Create one variable of each of the four basic Python types:
#   int, float, str, bool
# Print each variable along with its type using type().

# Solution:
whole_number = 10
decimal_number = 3.14
text = "Python"
flag = True

print(whole_number, "->", type(whole_number))
print(decimal_number, "->", type(decimal_number))
print(text, "->", type(text))
print(flag, "->", type(flag))

# Output:
# 10 -> <class 'int'>
# 3.14 -> <class 'float'>
# Python -> <class 'str'>
# True -> <class 'bool'>
