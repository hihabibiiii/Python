# Question 8 (Medium):
# Create a complex number z = 3 + 4j.
# Print its real part, imaginary part, and type.

# Solution:
z = 3 + 4j
print("Complex number:", z)
print("Real part:", z.real)
print("Imaginary part:", z.imag)
print("Type:", type(z))

# Output:
# Complex number: (3+4j)
# Real part: 3.0
# Imaginary part: 4.0
# Type: <class 'complex'>
