# Question 13 (Hard):
# Create a variable `total = 0`.
# Add the values 15, 25, 35, and 45 one by one using the += operator.
# Print the running total after each addition.

# Solution:
total = 0

total += 15
print("After adding 15: total =", total)

total += 25
print("After adding 25: total =", total)

total += 35
print("After adding 35: total =", total)

total += 45
print("After adding 45: total =", total)

# Output:
# After adding 15: total = 15
# After adding 25: total = 40
# After adding 35: total = 75
# After adding 45: total = 120
