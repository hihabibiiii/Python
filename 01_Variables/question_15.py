# Question 15 (Hard):
# Take marks for 3 subjects from the user using input().
# Store each mark in a separate variable.
# Compute and print the average mark.

# Solution:
mark1 = float(input("Enter mark for Subject 1: "))
mark2 = float(input("Enter mark for Subject 2: "))
mark3 = float(input("Enter mark for Subject 3: "))

average = (mark1 + mark2 + mark3) / 3
print("Average mark:", average)

# Example Input / Output:
# Enter mark for Subject 1: 80
# Enter mark for Subject 2: 75
# Enter mark for Subject 3: 90
# Average mark: 81.66666666666667
