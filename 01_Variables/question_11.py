# Question 11 (Hard):
# Create variables for a student: name, age, grade (letter), and marks (out of 100).
# Print a neatly formatted student report using these variables.

# Solution:
student_name = "Jordan Lee"
student_age = 17
student_grade = "A"
student_marks = 92

print("===== Student Report =====")
print("Name  :", student_name)
print("Age   :", student_age)
print("Grade :", student_grade)
print("Marks :", student_marks, "/ 100")
print("==========================")

# Output:
# ===== Student Report =====
# Name  : Jordan Lee
# Age   : 17
# Grade : A
# Marks : 92 / 100
# ==========================
