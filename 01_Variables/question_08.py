counter = counter + 1
print("Counter:", counter)

counter = counter + 1
print("Counter:", counter)

counter = counter + 1
print("Counter:", counter)

counter = counter + 1
print("Counter:", counter)

counter = counter + 1
print("Counter:", counter)

# Output:
# Counter: 1
# Counter: 2
# Counter: 3
# Counter: 4
# Counter: 5
