# Question 6 (Medium):
# Create a variable `price = 49.99` and `discount = 5.0`.
# Compute the final price after applying the discount.
# Print the original price, discount, and final price with labels.

# Solution:
price = 49.99
discount = 5.0
final_price = price - discount
print("Original Price:", price)
print("Discount:", discount)
print("Final Price:", final_price)

# Output:
# Original Price: 49.99
# Discount: 5.0
# Final Price: 44.99
