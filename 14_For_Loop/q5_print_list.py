# Question:
# Print all items in the following list of fruits using a for loop.
#   fruits = ['apple', 'banana', 'cherry', 'date', 'elderberry']
#
# Expected Output:
#   apple
#   banana
#   cherry
#   date
#   elderberry

fruits = ['apple', 'banana', 'cherry', 'date', 'elderberry']

print("List of fruits:")
for fruit in fruits:
    print(fruit)
