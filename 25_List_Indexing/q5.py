# Question: Modify the element at index 2 of a list.
# Lists are mutable; you can change an element by assigning to its index.
# Example:
#   Before: ['cat', 'dog', 'bird', 'fish']
#   Change index 2 to 'rabbit'
#   After:  ['cat', 'dog', 'rabbit', 'fish']

animals = ["cat", "dog", "bird", "fish"]
print("Original list:", animals)

animals[2] = "rabbit"
print("After modifying index 2:", animals)
