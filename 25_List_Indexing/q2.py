# Question: Access the last element of a list using a negative index (-1).
# Negative indexing counts from the end: -1 is the last, -2 is second-to-last, etc.
# Example:
#   List: [100, 200, 300, 400, 500]
#   Output: 500

numbers = [100, 200, 300, 400, 500]
print("List:", numbers)
print("Last element (index -1):", numbers[-1])
print("Second-to-last (index -2):", numbers[-2])
