# Question: Change the second element of a list.
# Lists are mutable — you can update elements by assigning to an index.
# Example:
#   Before: ['red', 'green', 'blue']
#   After:  ['red', 'yellow', 'blue']

colors = ["red", "green", "blue"]
print("Original list:", colors)

colors[1] = "yellow"
print("After changing index 1:", colors)
