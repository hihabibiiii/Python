# Question: Concatenate two lists and print the result.
# Use the + operator to join two lists into one.
# Example:
#   list1 = [1, 2, 3]
#   list2 = [4, 5, 6]
#   Result: [1, 2, 3, 4, 5, 6]

list1 = [1, 2, 3]
list2 = [4, 5, 6]

combined = list1 + list2
print("List 1:", list1)
print("List 2:", list2)
print("Concatenated:", combined)
