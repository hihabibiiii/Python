# Question: Access the first and last elements of a list.
# Use index 0 for the first element and index -1 for the last.
# Example:
#   List: [10, 20, 30, 40, 50]
#   First: 10, Last: 50

numbers = [10, 20, 30, 40, 50]
print("List:", numbers)
print("First element:", numbers[0])
print("Last element:", numbers[-1])
