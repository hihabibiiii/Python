# Question: Slice the first 3 elements of a list.
# Use slicing with [:3] to get elements at indices 0, 1, 2.
# Example:
#   List: [10, 20, 30, 40, 50]
#   Output: [10, 20, 30]

numbers = [10, 20, 30, 40, 50]
print("Full list:", numbers)
first_three = numbers[:3]
print("First 3 elements:", first_three)
