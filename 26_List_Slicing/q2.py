# Question: Slice the last 3 elements of a list.
# Use negative slicing with [-3:] to get the last 3 elements.
# Example:
#   List: [10, 20, 30, 40, 50]
#   Output: [30, 40, 50]

numbers = [10, 20, 30, 40, 50]
print("Full list:", numbers)
last_three = numbers[-3:]
print("Last 3 elements:", last_three)
