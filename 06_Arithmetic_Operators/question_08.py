# Question 8 (Medium):
# Take a number from the user.
# Compute and print its square (n**2) and cube (n**3).

# Solution:
number = float(input("Enter a number: "))
square = number ** 2
cube = number ** 3
print(f"Number : {number}")
print(f"Square : {number}^2 = {square}")
print(f"Cube   : {number}^3 = {cube}")

# Example:
# Enter a number: 5
# Number : 5.0
# Square : 5.0^2 = 25.0
# Cube   : 5.0^3 = 125.0
