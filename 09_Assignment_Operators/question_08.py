# Question:
# Start with x = 2.
# Apply **= 2 three times (raising to power of 2 each time).
# Print the value after each step.

# Example Output:
# After **=2 step 1: x = 4
# After **=2 step 2: x = 16
# After **=2 step 3: x = 256

x = 2
x **= 2
print(f"After **=2 step 1: x = {x}")
x **= 2
print(f"After **=2 step 2: x = {x}")
x **= 2
print(f"After **=2 step 3: x = {x}")
