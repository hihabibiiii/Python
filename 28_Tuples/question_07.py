# Question:
# Create a tuple of 2 elements and repeat it 3 times using *.
# Print the result.

# Example Output:
# Original: ('hello', 42)
# Repeated 3 times: ('hello', 42, 'hello', 42, 'hello', 42)

original = ("hello", 42)
repeated = original * 3

print(f"Original: {original}")
print(f"Repeated 3 times: {repeated}")
