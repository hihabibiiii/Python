# Question:
# Create two tuples and concatenate them using the + operator.
# Print the result.

# Example Output:
# Tuple 1: (1, 2, 3)
# Tuple 2: (4, 5, 6)
# Concatenated: (1, 2, 3, 4, 5, 6)

t1 = (1, 2, 3)
t2 = (4, 5, 6)
combined = t1 + t2

print(f"Tuple 1: {t1}")
print(f"Tuple 2: {t2}")
print(f"Concatenated: {combined}")
