# Question:
# Create a tuple of 5 colors and print it.
# Also print the type and length of the tuple.

# Example Output:
# Colors: ('red', 'blue', 'green', 'yellow', 'purple')
# Type: <class 'tuple'>
# Length: 5

colors = ("red", "blue", "green", "yellow", "purple")
print(f"Colors: {colors}")
print(f"Type: {type(colors)}")
print(f"Length: {len(colors)}")
