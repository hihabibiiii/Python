# Question:
# Create a tuple with 3 values (name, age, city).
# Unpack the tuple into 3 separate variables and print each.

# Example Output:
# Name: Alice
# Age: 25
# City: London

person = ("Alice", 25, "London")
name, age, city = person

print(f"Name: {name}")
print(f"Age: {age}")
print(f"City: {city}")
